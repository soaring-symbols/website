// Writes app/data/land-dots.ts: which dots of the hero globe's grid fall on
// land, packed one bit per dot. A one-off; to run it again:
//   npm i --no-save d3-geo topojson-client world-atlas
//   node scripts/land-dots.mjs
import { writeFileSync } from 'node:fs'
import { geoContains } from 'd3-geo'
import { feature } from 'topojson-client'
import world from 'world-atlas/land-110m.json' with { type: 'json' }

// Degrees between rows, and between dots along a row at the equator
const STEP = 1.2

const land = feature(world, world.objects.land)
const bits = []
const rows = Math.round(180 / STEP)
for (let r = 0; r < rows; r++) {
  const lat = 90 - (r + 0.5) * STEP
  // Fewer dots towards the poles, so they sit evenly on the sphere
  const cols = Math.max(
    1,
    Math.round((360 / STEP) * Math.cos((lat * Math.PI) / 180)),
  )
  for (let c = 0; c < cols; c++) {
    const lon = -180 + ((c + 0.5) * 360) / cols
    bits.push(geoContains(land, [lon, lat]) ? 1 : 0)
  }
}

const bytes = new Uint8Array(Math.ceil(bits.length / 8))
bits.forEach((bit, i) => {
  if (bit) bytes[i >> 3] |= 128 >> (i & 7)
})

writeFileSync(
  new URL('../app/data/land-dots.ts', import.meta.url),
  `// Generated by scripts/land-dots.mjs from Natural Earth's 1:110m land
// (world-atlas): one bit per dot of the hero globe's grid, 1 on land
export const LAND_STEP = ${STEP}
export const LAND_DOTS =
  '${Buffer.from(bytes).toString('base64')}'
`,
)
console.log(`${bits.length} dots, ${bits.filter(Boolean).length} on land`)
