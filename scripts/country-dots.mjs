// Writes app/data/country-dots.ts: which land dots of the hero globe's grid
// (the one scripts/land-dots.mjs walks) fall in each country, for the
// airline page's globe to show the airline's country in its color. A
// country too small to hold a dot (Sint Maarten) gets the dot nearest its
// middle. A one-off; to run it again:
//   npm i --no-save d3-geo topojson-client world-atlas i18n-iso-countries
//   node scripts/country-dots.mjs
import { writeFileSync } from 'node:fs'
import { geoBounds, geoCentroid, geoContains } from 'd3-geo'
import { feature } from 'topojson-client'
import countries from 'i18n-iso-countries'
import landAtlas from 'world-atlas/land-50m.json' with { type: 'json' }
import countryAtlas from 'world-atlas/countries-50m.json' with { type: 'json' }

// The land dots' grid: keep in step with scripts/land-dots.mjs
const STEP = 0.6
const RAD = Math.PI / 180

const land = feature(landAtlas, landAtlas.objects.land)
const shapes = feature(countryAtlas, countryAtlas.objects.countries)
  .features.map((shape) => ({
    shape,
    code: countries.numericToAlpha2(shape.id),
    bounds: geoBounds(shape),
  }))
  .filter(({ code }) => code)

// Whether a point is inside a country's bounds, which may cross the
// antimeridian
function inBounds([[west, south], [east, north]], lon, lat) {
  if (lat < south || lat > north) return false

  return west <= east ? lon >= west && lon <= east : lon >= west || lon <= east
}

const rows = Array.from({ length: Math.round(180 / STEP) }, (_, r) => {
  const lat = 90 - (r + 0.5) * STEP
  const cols = Math.max(1, Math.round((360 / STEP) * Math.cos(lat * RAD)))

  return { lat, cols }
})

// Each country's dots, by their index in the grid
const dots = new Map(shapes.map(({ code }) => [code, []]))
let index = 0
for (const { lat, cols } of rows) {
  for (let c = 0; c < cols; c++, index++) {
    const lon = -180 + ((c + 0.5) * 360) / cols
    if (!geoContains(land, [lon, lat])) continue
    const found = shapes.find(
      ({ shape, bounds }) =>
        inBounds(bounds, lon, lat) && geoContains(shape, [lon, lat]),
    )
    if (found) dots.get(found.code).push(index)
  }
}

// The grid's dot nearest a point
function nearestDot(lon, lat) {
  const r = Math.min(rows.length - 1, Math.floor((90 - lat) / STEP))
  const before = rows.slice(0, r).reduce((sum, row) => sum + row.cols, 0)
  const c = Math.floor(((lon + 180) / 360) * rows[r].cols) % rows[r].cols

  return before + c
}

for (const { shape, code } of shapes) {
  if (!dots.get(code).length)
    dots.get(code).push(nearestDot(...geoCentroid(shape)))
}

// Unsigned numbers seven bits a byte, the high bit set on all but the last
function varint(n, out) {
  while (n > 127) {
    out.push((n & 127) | 128)
    n >>>= 7
  }
  out.push(n)
}

// Each country's dots as runs of neighbours: how many dots after the last
// run (or the grid's start) the run begins, then how long it is
function encode(list) {
  const out = []
  const sorted = [...new Set(list)].sort((a, b) => a - b)
  let end = 0
  for (let i = 0; i < sorted.length;) {
    let j = i
    while (sorted[j + 1] === sorted[j] + 1) j++
    varint(sorted[i] - end, out)
    varint(j - i + 1, out)
    end = sorted[j] + 1
    i = j + 1
  }

  return Buffer.from(out).toString('base64')
}

const entries = [...dots]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([code, list]) => `  ${code}: '${encode(list)}',`)

writeFileSync(
  new URL('../app/data/country-dots.ts', import.meta.url),
  `// Generated by scripts/country-dots.mjs from Natural Earth's 1:50m
// countries and land (world-atlas): each country's dots on the hero globe's
// grid, by ISO 3166-1 alpha-2 code, as base64 runs of varints (dots skipped
// since the last run, then dots in the run)
export const COUNTRY_DOTS: Record<string, string> = {
${entries.join('\n')}
}
`,
)
